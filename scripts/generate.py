#!/usr/bin/env python3
"""Generate conservative endpoint types from a self-contained contract.

Unsupported schema combinations become unknown/Any, never a falsely narrow type.
Schema enforcement is optional; generated types describe the declared contract.
"""
import argparse
import json
import keyword
from pathlib import Path

def ts(schema):
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"]) or "never"
    if any(k in schema for k in ("anyOf", "oneOf", "allOf", "$ref")):
        return "unknown"
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(ts(dict(schema, type=k)) for k in kind)
    if kind == "array":
        return f"Array<{ts(schema.get('items', {}))}>"
    if kind == "object":
        required = schema.get("required", [])
        fields = [f"{json.dumps(k)}{'' if k in required else '?'}: {ts(v)}" for k,v in schema.get("properties", {}).items()]
        if schema.get("additionalProperties", True) is not False:
            fields.append("[key: string]: unknown")
        return "{ " + "; ".join(fields) + " }" if fields else "Record<string, never>"
    return {"string":"string","integer":"number","number":"number","boolean":"boolean","null":"null"}.get(kind,"unknown")

def generate(contract, destination):
    if contract.get("version") != 2:
        raise ValueError("expected contract version 2")
    destination.mkdir(parents=True, exist_ok=True)
    types = ["// Generated by scripts/generate.py. Schema enforcement is optional; these types describe the declared contract.", "export type API = {"]
    for e in contract["endpoints"]:
        types.append(f"  {json.dumps(e['name'])}: {{ input: {ts(e['input'])}; output: {ts(e['output'])} }};")
    types.append("};\nexport type Streams = {")
    for s in contract.get("streams", []):
        types.append(f"  {json.dumps(s['name'])}: {{ input: {ts(s['input'])} }};")
    types.append("};\n")
    (destination / "contract.ts").write_text("\n".join(types))
    definitions=[]
    def py(schema, name):
        kind=schema.get("type")
        if isinstance(kind,list) or any(k in schema for k in ("anyOf","oneOf","allOf","$ref")):
            return "Any"
        if kind=="object":
            required=schema.get("required",[])
            fields=[]
            for index,(key,value) in enumerate(schema.get("properties",{}).items()):
                typ=py(value,name+str(index))
                if key not in required:
                    typ=f"NotRequired[{typ}]"
                fields.append(f"{key!r}: {typ}")
            if schema.get("additionalProperties",True) is not False:
                return "Dict[str, Any]"
            definitions.append(f"{name} = TypedDict({name!r}, {{{', '.join(fields)}}})")
            return name
        if kind=="array":
            return f"List[{py(schema.get('items',{}),name+'Item')}]"
        return {"string":"str","number":"float","integer":"int","boolean":"bool","null":"None"}.get(kind,"Any")
    methods=[]
    for i,e in enumerate(contract["endpoints"]):
        # Contract validation already requires SQL-safe endpoint identifiers.
        if not e["name"].isidentifier() or e["name"].startswith("_") or keyword.iskeyword(e["name"]):
            raise ValueError("Python endpoint name is not a public identifier")
        inp=py(e["input"],f"Input{i}");out=py(e["output"],f"Output{i}")
        methods.append(f"    def {e['name']}(self, data: {inp}) -> {out}:\n        return self._client.call({e['name']!r}, data)\n")
    python=["# Generated by scripts/generate.py.","from typing import Any, Dict, List, TypedDict", "from typing_extensions import NotRequired", "from pgxio import Client", *definitions,"\nclass API:","    def __init__(self, client: Client):\n        self._client = client\n",*methods]
    (destination/"contract.py").write_text("\n".join(python)+"\n")

if __name__=="__main__":
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("contract",type=Path)
    p.add_argument("destination",type=Path)
    args=p.parse_args()
    generate(json.loads(args.contract.read_text()),args.destination)
